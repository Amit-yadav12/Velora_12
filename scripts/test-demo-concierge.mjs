import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom = new JSDOM('', { url: 'http://localhost/' });
globalThis.window = dom.window;
globalThis.localStorage = dom.window.localStorage;
globalThis.document = dom.window.document;
globalThis.fetch = () => { throw new Error('Demo concierge must not contact the network'); };
const { demoConcierge } = await import('../src/lib/demoConcierge.ts');
const { istTomorrow } = await import('../src/lib/format.ts');
const first = demoConcierge('Find the nearest salon', 'Jaipur');
assert.match(first.reply, /sample suggestion/i);
assert.match(first.reply, /can't verify which is nearest/i);
assert.ok(first.selectedId?.startsWith('demo-biz-'));
assert.match(first.action.to, /^\/business\/demo-biz-/);
const follow = demoConcierge('ok book an appointment', 'Jaipur', first.selectedId);
assert.equal(follow.selectedId, first.selectedId);
assert.match(follow.reply, /no appointment has been made/i);
assert.equal(follow.action.type, 'book');
assert.equal(follow.action.to, `/business/${first.selectedId}`);
const future = demoConcierge('Book a dentist tomorrow afternoon', 'Jaipur');
assert.equal(future.action.type, 'book');
assert.ok(future.action.to.includes(`date=${istTomorrow()}`));
assert.ok(future.action.to.includes('hour=14'));
assert.equal(demoConcierge('Show my appointments', 'Jaipur').action.to, '/appointments');
assert.equal(demoConcierge('Reschedule my booking', 'Jaipur').action.to, '/appointments');
assert.match(demoConcierge('directions to the salon', 'Jaipur').reply, /not available/i);
const unknown = demoConcierge('book a dentist', 'Jaipur', first.selectedId);
assert.notEqual(unknown.selectedId, first.selectedId, 'a new category must not silently reuse a previous business');
assert.equal(localStorage.getItem('velora-local-bookings'), null, 'assistant never makes a booking');
console.log('Demo concierge: local-only suggestions, follow-up, IST date, booking navigation and safe actions passed.');
dom.window.close();
